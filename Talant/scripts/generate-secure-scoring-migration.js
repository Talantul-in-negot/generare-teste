'use strict';

// Generates the seed portion of the secure scoring migration from the
// checked-in question banks. The generated SQL is committed so the database
// never needs to read browser assets at runtime.
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const root = path.resolve(__dirname, '..');
const testFiles = [
  ['samuel1-3-v2', '1samuel-1-3.js'], ['samuel4-6-v2', '1samuel-4-6.js'],
  ['samuel7-9-v2', '1samuel-7-9.js'], ['samuel10-12-v2', '1samuel-10-12.js'],
  ['samuel13-15-v2', '1samuel-13-15.js'], ['samuel16-18-v2', '1samuel-16-18.js'],
  ['samuel19-21-v2', '1samuel-19-21.js'], ['samuel22-24-v2', '1samuel-22-24.js'],
  ['samuel25-27-v2', '1samuel-25-27.js'], ['samuel28-30-v2', '1samuel-28-30.js'],
  ['samuel31-2samuel1-2-v2', '1samuel31-2samuel1-2.js'], ['2samuel3-5-v2', '2samuel-3-5.js'],
  ['2samuel6-8-v2', '2samuel-6-8.js'], ['2samuel9-11-v2', '2samuel-9-11.js'],
  ['2samuel12-14-v2', '2samuel-12-14.js'], ['2samuel15-17-v2', '2samuel-15-17.js'],
  ['2samuel18-20-v2', '2samuel-18-20.js'], ['2samuel21-24-v2', '2samuel-21-24.js'],
];
function load(file, name) {
  const source = fs.readFileSync(file, 'utf8').replace(new RegExp(`\\bconst\\s+${name}\\s*=`), `${name} =`);
  const context = {};
  vm.createContext(context);
  vm.runInContext(source, context, { timeout: 1000 });
  return context[name];
}
function sqlString(value) { return `'${String(value).replace(/'/g, "''")}'`; }
function json(value) { return `${sqlString(JSON.stringify(value))}::jsonb`; }
function testRows(version, data) {
  return data.sections.flatMap(section => {
    const items = section.type === 'match' ? section.left : section.items;
    return items.map((item, index) => {
      const answer = section.type === 'multi' ? [...item.correct].sort() : item.correct;
      return `(${sqlString(version)}, ${sqlString(section.id)}, ${index}, ${json(answer)}, ${section.points})`;
    });
  });
}
const questions = load(path.join(root, 'questions.js'), 'QUESTIONS');
const quizRows = questions.map((question, index) =>
  `('ioan-v2', ${index}, ${json(Array.isArray(question.correct) ? [...question.correct].sort((a, b) => a - b) : [question.correct])})`
);
const tests = testFiles.flatMap(([version, file]) => {
  const source = fs.readFileSync(path.join(root, 'data', file), 'utf8');
  const identifier = /const\s+(TEST_[A-Z0-9_]+)\s*=/.exec(source)?.[1];
  if (!identifier) throw new Error(`Missing test constant in ${file}`);
  return testRows(version, load(path.join(root, 'data', file), identifier));
});
const template = fs.readFileSync(path.join(__dirname, 'secure-scoring-template.sql'), 'utf8');
const output = `-- Generated by scripts/generate-secure-scoring-migration.js. Do not edit manually.\n-- Apply this after the existing Talant scoring migrations.\n\n${template}\n\ninsert into public.talant_quiz_answer_keys (quiz_version, question_id, correct_indices) values\n${quizRows.join(',\n')}\non conflict (quiz_version, question_id) do update set correct_indices = excluded.correct_indices;\n\ninsert into public.talant_test_answer_keys (quiz_version, section_id, item_index, correct_answer, points) values\n${tests.join(',\n')}\non conflict (quiz_version, section_id, item_index) do update set correct_answer = excluded.correct_answer, points = excluded.points;\n\ncommit;\n`;
fs.writeFileSync(path.join(root, 'supabase', '20260824_secure_scoring.sql'), output);
console.log(`Generated ${quizRows.length} quiz keys and ${tests.length} test keys.`);
