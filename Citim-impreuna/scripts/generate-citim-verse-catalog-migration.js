/* Generates the committed catalog seed from the published verse corpus. */
const fs = require("fs");
const path = require("path");
const vm = require("vm");

function loadVerseArray(fileName, globalName) {
  const source = fs.readFileSync(fileName, "utf8");
  const context = {};
  vm.createContext(context);
  vm.runInContext(`${source}\nglobalThis.__verses = ${globalName};`, context, { filename: fileName });
  return context.__verses;
}

const root = path.resolve(__dirname, "..");
const verses = [
  ...loadVerseArray(path.join(root, "js", "verses-1samuel.js"), "VERSES_1SAMUEL"),
  ...loadVerseArray(path.join(root, "js", "verses-2samuel.js"), "VERSES_2SAMUEL"),
];
const PAGE_SIZE = 5;
const chapterSizes = new Map();
for (const verse of verses) {
  const chapterRef = verse.ref.replace(/:\d+$/, "");
  chapterSizes.set(chapterRef, (chapterSizes.get(chapterRef) || 0) + 1);
}
const catalog = verses.map((verse, index) => {
  if (!Array.isArray(verse.blanks) || verse.blanks.length !== 1) throw new Error(`${verse.ref}: expected one blank`);
  const blank = verse.blanks[0];
  if (!Array.isArray(blank.options) || !blank.options.includes(blank.answer)) throw new Error(`${verse.ref}: invalid options`);
  const chapter_ref = verse.ref.replace(/:\d+$/, "");
  return {
    verse_ref: verse.ref,
    correct_answer: blank.answer,
    valid_choices: blank.options,
    page_index: Math.floor(index / PAGE_SIZE),
    page_size: Math.min(PAGE_SIZE, verses.length - Math.floor(index / PAGE_SIZE) * PAGE_SIZE),
    chapter_ref,
    chapter_size: chapterSizes.get(chapter_ref),
  };
});

const lines = [
  "-- Generated by scripts/generate-citim-verse-catalog-migration.js. Do not edit the JSON payload manually.",
  "-- It is a snapshot of js/verses-1samuel.js and js/verses-2samuel.js at generation time.",
  "",
  "begin;",
  "",
  "alter table public.events add column if not exists client_event_id uuid;",
  "create unique index if not exists events_user_client_event_id_idx on public.events(user_id, client_event_id) where client_event_id is not null;",
  "",
  "create table if not exists public.citim_verse_catalog (",
  "  verse_ref text primary key,",
  "  correct_answer text not null,",
  "  valid_choices text[] not null check (cardinality(valid_choices) = 4),",
  "  page_index integer not null check (page_index >= 0),",
  "  page_size smallint not null check (page_size between 1 and 5),",
  "  chapter_ref text not null,",
  "  chapter_size smallint not null check (chapter_size between 1 and 100)",
  ");",
  "",
  "alter table public.citim_verse_catalog enable row level security;",
  "revoke all on table public.citim_verse_catalog from public, anon, authenticated;",
  "",
  "insert into public.citim_verse_catalog (verse_ref, correct_answer, valid_choices, page_index, page_size, chapter_ref, chapter_size)",
  "select verse_ref, correct_answer, valid_choices, page_index, page_size, chapter_ref, chapter_size",
  "from jsonb_to_recordset($catalog$" + JSON.stringify(catalog) + "$catalog$::jsonb) as catalog(",
  "  verse_ref text, correct_answer text, valid_choices text[], page_index integer, page_size smallint, chapter_ref text, chapter_size smallint",
  ")",
  "on conflict (verse_ref) do update set",
  "  correct_answer = excluded.correct_answer, valid_choices = excluded.valid_choices, page_index = excluded.page_index,",
  "  page_size = excluded.page_size, chapter_ref = excluded.chapter_ref, chapter_size = excluded.chapter_size;",
  "",
  "create or replace function public.validate_citim_event_insert()",
  "returns trigger language plpgsql security definer set search_path = public, pg_temp as $function$",
  "declare",
  "  v_answer text; v_choices text[]; v_page_index integer; v_page_size smallint;",
  "  v_chapter_ref text; v_chapter_size smallint; v_now timestamptz := clock_timestamp();",
  "begin",
  "  if auth.uid() is null or new.user_id is distinct from auth.uid() then",
  "    raise exception 'Events may only be created for the authenticated user';",
  "  end if;",
  "  select c.correct_answer, c.valid_choices, c.page_index, c.page_size, c.chapter_ref, c.chapter_size",
  "    into v_answer, v_choices, v_page_index, v_page_size, v_chapter_ref, v_chapter_size",
  "    from public.citim_verse_catalog c where c.verse_ref = new.verse_ref;",
  "  if not found then raise exception 'Unknown verse reference'; end if;",
  "  if new.chosen is null or not (new.chosen = any(v_choices)) then",
  "    raise exception 'Chosen answer is not a valid option for this verse';",
  "  end if;",
  "  if new.answer is distinct from v_answer then",
  "    raise exception 'Submitted answer does not match the canonical answer';",
  "  end if;",
  "  if new.correct is distinct from (new.chosen = v_answer) then",
  "    raise exception 'Submitted correctness does not match the chosen answer';",
  "  end if;",
  "  if coalesce(new.cycle, 0) < 0 then raise exception 'Cycle must not be negative'; end if;",
  "  -- Do not permit the browser to choose scoring metadata or event times.",
  "  new.page_index := v_page_index; new.page_size := v_page_size;",
  "  new.chapter_ref := v_chapter_ref; new.chapter_size := v_chapter_size;",
  "  new.recorded_at := v_now; new.created_at := v_now;",
  "  new.user_name := coalesce(nullif(trim(auth.jwt() -> 'user_metadata' ->> 'username'), ''), nullif(trim(new.user_name), ''), 'Utilizator');",
  "  return new;",
  "end;",
  "$function$;",
  "",
  "drop trigger if exists events_validate_citim_insert on public.events;",
  "create trigger events_validate_citim_insert before insert on public.events for each row",
  "execute function public.validate_citim_event_insert();",
  "revoke all on function public.validate_citim_event_insert() from public;",
  "",
  "drop function if exists public.get_public_leaderboard(integer);",
  "create function public.get_public_leaderboard(p_limit integer default 5)",
  "returns table(user_name text, points integer)",
  "language sql security definer set search_path = public, pg_temp as $function$",
  "  select s.user_name::text, s.points::integer",
  "  from public.scores s join auth.users u on u.id = s.user_id",
  "  where auth.uid() is not null and s.user_name is not null",
  "    and lower(u.email) like '%@' || (case when lower(auth.jwt() ->> 'email') like '%@citim.app' then 'citim.app' else 'test.com' end)",
  "  order by s.points desc, s.user_name asc",
  "  limit greatest(1, least(coalesce(p_limit, 5), 1000));",
  "$function$;",
  "revoke all on function public.get_public_leaderboard(integer) from public, anon;",
  "grant execute on function public.get_public_leaderboard(integer) to authenticated;",
  "",
  "create or replace function public.get_own_score()",
  "returns integer language sql security definer set search_path = public, pg_temp as $function$",
  "  select coalesce(s.points, 0)::integer from public.scores s where s.user_id = auth.uid() limit 1;",
  "$function$;",
  "revoke all on function public.get_own_score() from public, anon;",
  "grant execute on function public.get_own_score() to authenticated;",
  "",
  "commit;",
  "",
];

const out = path.join(root, "supabase", "20260824_secure_event_validation.sql");
fs.writeFileSync(out, lines.join("\n"));
console.log(`Wrote ${out} with ${catalog.length} catalog rows.`);
